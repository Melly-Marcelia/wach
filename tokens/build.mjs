// Turns tokens/tokens.json (W3C Design Tokens format) into src/styles/tokens.css.
//   primitive.color.navy.900  → --p-color-navy-900
//   semantic.color.text       → --color-text        (references stay linked: var(--p-…))
//   semantic.type.body        → --type-body (font shorthand) + --type-body-tracking + .type-body class
// No dependencies, so it runs anywhere Node runs: `npm run tokens`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'))
const OUT = resolve(root, 'src/styles/tokens.css')

// Walk the tree, collecting leaf tokens (objects with $value) and inheriting $type.
function collect(node, path = [], type) {
  const out = []
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$') || typeof val !== 'object') continue
    const t = val.$type || type
    if ('$value' in val) out.push({ path: [...path, key], value: val.$value, type: t, description: val.$description })
    else out.push(...collect(val, [...path, key], t))
  }
  return out
}

const all = collect(tokens)
const byPath = new Map(all.map((t) => [t.path.join('.'), t]))

// semantic.* drops its layer name; primitive.* gets a p- prefix.
const varName = (path) => {
  const [layer, group, ...rest] = path
  if (layer === 'primitive') return `--p-${[group, ...rest].join('-')}`
  if (group === 'motion') return `--${rest.join('-')}`
  return `--${[group, ...rest].join('-')}`
}

const refPattern = /\{([^}]+)\}/g
const isRef = (v) => typeof v === 'string' && /^\{[^}]+\}$/.test(v)
const deref = (v) => byPath.get(v.slice(1, -1))

const family = (v) => v.map((f) => (/\s/.test(f) && !f.includes('-apple') ? `'${f}'` : f)).join(', ')

function cssValue(token) {
  const { value, type } = token
  if (isRef(value)) return `var(${varName(deref(value).path)})`
  if (typeof value === 'string') return value.replace(refPattern, (_, p) => `var(${varName(p.split('.'))})`)
  if (type === 'fontFamily') return family(value)
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`
  return String(value)
}

// Typography composites resolve to a `font` shorthand plus a tracking variable.
function typeParts(token) {
  const v = token.value
  const r = (x) => (isRef(x) ? `var(${varName(deref(x).path)})` : x)
  return { font: `${r(v.fontWeight)} ${v.fontSize}/${v.lineHeight} ${r(v.fontFamily)}`, tracking: v.letterSpacing }
}

const lines = []
const typeClasses = []
let lastGroup = ''
for (const t of all) {
  const group = t.path.slice(0, 2).join('.')
  if (group !== lastGroup) {
    lines.push(`\n  /* ${group} */`)
    lastGroup = group
  }
  const name = varName(t.path)
  const note = t.description ? ` /* ${t.description} */` : ''
  if (t.type === 'typography') {
    const { font, tracking } = typeParts(t)
    lines.push(`  ${name}: ${font};${note}`, `  ${name}-tracking: ${tracking};`)
    const role = t.path.at(-1)
    const extra = [
      role === 'overline' ? 'text-transform: uppercase;' : '',
      role.startsWith('numeric') ? 'font-variant-numeric: tabular-nums;' : '',
    ].filter(Boolean).join(' ')
    typeClasses.push(`.type-${role} { font: var(${name}); letter-spacing: var(${name}-tracking);${extra ? ' ' + extra : ''} }`)
  } else {
    lines.push(`  ${name}: ${cssValue(t)};${note}`)
  }
}

const css = `/* GENERATED by tokens/build.mjs from tokens/tokens.json. Do not edit by hand. */
:root {${lines.join('\n')}
}

/* Text styles: one class per type role. */
${typeClasses.join('\n')}
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, css)
console.log(`tokens: ${all.length} tokens → ${OUT.replace(root + '/', '')}`)
